export const DEFAULT_LONDOND_COORDINATES = { lat: 51.513, lng: -0.136 }; // Central Soho

export function resolvePostcode(postcode: string): { lat: number; lng: number } {
  const clean = postcode.toUpperCase().trim();
  if (!clean) return DEFAULT_LONDOND_COORDINATES;

  // Check if starts with a double coordinate syntax e.g., "51.5225, -0.1014"
  const matchesCoords = clean.match(/^([+-]?\d+\.?\d*)\s*,\s*([+-]?\d+\.?\d*)$/);
  if (matchesCoords) {
    const lat = parseFloat(matchesCoords[1]);
    const lng = parseFloat(matchesCoords[2]);
    if (!isNaN(lat) && !isNaN(lng)) {
      return { lat, lng };
    }
  }

  // Check postal sector prefix (e.g. "EC1A 1BB" -> "EC1", "E1 6RF" -> "E1")
  const part = clean.split(' ')[0];
  const alphaNumericPrefix = part.match(/^([A-Z]+[0-9]+)/)?.[1];
  
  if (alphaNumericPrefix && LONDON_POSTCODES[alphaNumericPrefix]) {
    return LONDON_POSTCODES[alphaNumericPrefix];
  }
  
  // Try generic matching of just the first characters
  for (const [key, coords] of Object.entries(LONDON_POSTCODES)) {
    if (clean.startsWith(key)) {
      return coords;
    }
  }

  return DEFAULT_LONDOND_COORDINATES;
}
